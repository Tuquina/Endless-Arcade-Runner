// Offline generator for variantTable.ts. Run with `npm run gen:variants` (it is a vitest "test"
// only because vitest is the TypeScript runner this project already has).
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import { PREFABS } from './segments';
import { VARIANTS } from './variants';
import { bucketsOf, checkVariant, fingerprint } from './variantCheck';
import { World } from './World';

it('generate variant table', () => {
  const scratch = new World(256);
  const table: Record<string, Record<number, [number, number][]>> = {};
  const prints: Record<string, string> = {};
  const lines: string[] = [];
  for (const prefab of PREFABS.filter((p) => p.validate)) {
    table[prefab.id] = {};
    prints[prefab.id] = fingerprint(prefab, VARIANTS);
    const counts: string[] = [];
    for (const bucket of bucketsOf(prefab)) {
      const good: [number, number][] = [];
      for (let v = 0; v < VARIANTS; v++) {
        const verdict = checkVariant(prefab, v, bucket, scratch);
        if (verdict.ok) good.push([v, Math.min(999, Math.round(verdict.windowMs / 10))]);
      }
      good.sort((a, b) => b[1] - a[1]); // easiest (widest window) first
      table[prefab.id]![bucket] = good;
      counts.push(`${bucket}:${good.length}`);
    }
    lines.push(`${prefab.id.padEnd(14)} ${counts.join(' ')}`);
  }
  const body =
    '// Generated by `npm run gen:variants`. Do not edit by hand.\n' +
    `export const VARIANT_TABLE: Record<string, Record<number, [number, number][]>> = ${JSON.stringify(table)};\n` +
    `export const VARIANT_FINGERPRINTS: Record<string, string> = ${JSON.stringify(prints)};\n`;
  writeFileSync(new URL('./variantTable.ts', import.meta.url), body);
  console.log('\nvalid variants per bucket (of ' + VARIANTS + '):\n' + lines.join('\n'));
}, 3_600_000);
